def build_two_column_row(left, right, col_width=(CONTENT_WIDTH - 0.2 * inch) / 2, gap=0.2 * inch):
    """
    Lay two flowables side by side — the compact layout already used for the
    fee table, reused for the skills/behaviour rating tables.
    """
    from reportlab.lib import colors
    from reportlab.platypus import Table, TableStyle

    row_table = Table([[left, '', right if right is not None else '']], colWidths=[col_width, gap, col_width])
    row_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('TOPPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 0),
    ]))
    return row_table


def build_two_column_ratings(rating_pairs, col_width=(CONTENT_WIDTH - 0.2 * inch) / 2, gap=0.2 * inch):
    """Split a ratings list in half and lay the two halves side by side (see build_two_column_row)."""
    half = (len(rating_pairs) + 1) // 2
    col_widths = (col_width * 0.66, col_width * 0.34)
    left = build_ratings_table(rating_pairs[:half], col_widths=col_widths)
    right_pairs = rating_pairs[half:]
    right = build_ratings_table(right_pairs, col_widths=col_widths) if right_pairs else None
    return build_two_column_row(left, right, col_width=col_width, gap=gap)


class StudentComprehensiveReportGenerator(BaseReportGenerator):
    """Premium student progress report: profile, attendance, learning, assessment, fees, remarks."""

    def _date_range(self):
        """Parse date_from/date_to parameters into date objects, when both are present."""
        date_from = self.parameters.get('date_from')
        date_to = self.parameters.get('date_to')
        if not date_from or not date_to:
            return None, None
        try:
            return date.fromisoformat(date_from), date.fromisoformat(date_to)
        except (TypeError, ValueError):
            return None, None

    def _resolve_academic_year(self, date_from, academic_year_id):
        """Resolve which AcademicYear the fee chart's fixed 12-month window should anchor to."""
        from academic_sessions.models import AcademicYear

        if academic_year_id:
            ay = AcademicYear.objects.filter(id=academic_year_id, school=self.school).first()
            if ay:
                return ay
        if date_from:
            ay = AcademicYear.objects.filter(
                school=self.school, start_date__lte=date_from, end_date__gte=date_from,
            ).first()
            if ay:
                return ay
        return AcademicYear.objects.filter(school=self.school, is_current=True).first()

    @staticmethod
    def _month_sequence(start_date, end_date):
        """Return inclusive month sequence as (year, month) tuples from start_date to end_date."""
        sequence = []
        current = date(start_date.year, start_date.month, 1)
        end = date(end_date.year, end_date.month, 1)
        while current <= end:
            sequence.append((current.year, current.month))
            month = current.month + 1
            year = current.year
            if month > 12:
                month = 1
                year += 1
            current = date(year, month, 1)
        return sequence

    @staticmethod
    def _academic_year_month_order(academic_year_obj):
        """Map month number -> chronological order within the academic year window."""
        if not academic_year_obj or not academic_year_obj.start_date:
            return {month: month for month in range(1, 13)}

        months = StudentComprehensiveReportGenerator._twelve_months_from(academic_year_obj.start_date)
        return {month: index for index, (_year, month) in enumerate(months)}

    @staticmethod
    def _twelve_months_from(start_date):
        """List of 12 (year, month) tuples starting at start_date's month."""
        months = []
        y, m = start_date.year, start_date.month
        for _ in range(12):
            months.append((y, m))
            m += 1
            if m > 12:
                m = 1
                y += 1
        return months

    def _resolve_holiday_dates(self, months_list, class_obj_id):
        """Expand active school-calendar OFF_DAY entries into a set of individual dates."""
        if not months_list:
            return set()
        from academic_sessions.models import SchoolCalendarEntry

        first_y, first_m = months_list[0]
        last_y, last_m = months_list[-1]
        range_start = date(first_y, first_m, 1)
        range_end = date(last_y, last_m, calendar.monthrange(last_y, last_m)[1])

        entries = SchoolCalendarEntry.objects.filter(
            school=self.school,
            entry_kind=SchoolCalendarEntry.EntryKind.OFF_DAY,
            is_active=True,
            affects_students=True,
            start_date__lte=range_end,
            end_date__gte=range_start,
        ).prefetch_related('classes')

        holiday_dates = set()
        for entry in entries:
            if entry.scope == SchoolCalendarEntry.Scope.CLASS:
                class_ids = set(entry.classes.values_list('id', flat=True))
                if class_obj_id not in class_ids:
                    continue
            d = max(entry.start_date, range_start)
            end = min(entry.end_date, range_end)
            while d <= end:
                holiday_dates.add(d)
                d += timedelta(days=1)
        return holiday_dates

    def get_data(self):
        student_id = self.parameters.get('student_id')
        if not student_id:
            return {'error': 'No student specified'}

        academic_year_id = self._academic_year_id()
        date_from, date_to = self._date_range()

        from students.models import Student

        try:
            student = Student.objects.select_related('class_obj', 'school').get(id=student_id)
        except Student.DoesNotExist:
            return {'error': 'Student not found'}

        # A student transferred in from another branch is reported on across every branch they
        # have been at (students.timeline): earlier branches' attendance, fees, exams and
        # remarks are read in place, labelled, and cut at the leaving date. An ordinary
        # student keeps exactly the single-branch report.
        from students import timeline
        segments = timeline.student_timeline(student)
        has_history = len(segments) > 1
        earlier_branches = [s.school_name for s in segments if not s.is_current]

        enrollment_map = self._get_enrollment_map([student.id])
        class_name = self._resolve_class_name(student, enrollment_map)
        roll_number = self._resolve_roll_number(student, enrollment_map)

        # Resolve the academic year up front — it already anchors the fee chart's
        # fixed 12-month window below, and now also bounds the attendance query's
        # default window. Without this, a request with no explicit period pulled a
        # student's *entire* attendance history and built one reportlab calendar
        # table per month with any record — for a multi-year student that's dozens
        # of heavy Table objects per report, which is what let a bulk "Download
        # Reports" burst (many students, no period selected) push the single
        # 512MB web dyno into an OOM kill.
        academic_year_obj = self._resolve_academic_year(date_from, academic_year_id)

        # Placement for the report's year (class, section, roll). Without an
        # explicit year the map above is empty, so fall back to the year the
        # report resolves to rather than the Student snapshot (latest class).
        from academic_sessions.roster import placement_class_id, placements_for

        placement = enrollment_map.get(student.id)
        if placement is None and academic_year_obj:
            placement = placements_for(self.school.id, [(student.id, academic_year_obj.id)]).get(
                (student.id, academic_year_obj.id)
            )
            if placement is not None:
                enrollment_map = {student.id: placement}
                class_name = self._resolve_class_name(student, enrollment_map)
                roll_number = self._resolve_roll_number(student, enrollment_map)
        placement_class = placement_class_id(placement, student)

        # --- Attendance ---
        from attendance.models import AttendanceRecord
        att_qs = AttendanceRecord.objects.filter(student=student)
        if has_history:
            # Every branch's own days. Each branch has its own academic-year record, so the
            # window is by date (the report period, else the resolved academic year).
            att_qs = AttendanceRecord.objects.filter(timeline.attendance_q(segments))
            if date_from and date_to:
                att_qs = att_qs.filter(date__gte=date_from, date__lte=date_to)
            elif academic_year_obj:
                att_qs = att_qs.filter(date__gte=academic_year_obj.start_date, date__lte=academic_year_obj.end_date)
        elif date_from and date_to:
            att_qs = att_qs.filter(date__gte=date_from, date__lte=date_to)
        elif academic_year_id:
            att_qs = att_qs.filter(academic_year_id=academic_year_id)
        elif academic_year_obj:
            att_qs = att_qs.filter(academic_year_id=academic_year_obj.id)

        attendance_by_date = {rec.date: rec.status for rec in att_qs.only('date', 'status')}
        present = sum(1 for s in attendance_by_date.values() if s == AttendanceRecord.AttendanceStatus.PRESENT)
        absent = sum(1 for s in attendance_by_date.values() if s == AttendanceRecord.AttendanceStatus.ABSENT)
        leave = sum(1 for s in attendance_by_date.values() if s == AttendanceRecord.AttendanceStatus.LEAVE)
        total_days = len(attendance_by_date)
        att_rate = round(present / total_days * 100, 1) if total_days else 0
        attendance_months = sorted({(d.year, d.month) for d in attendance_by_date.keys()})

        # Legend entries reflect whatever status codes actually appear in the data,
        # not a hardcoded Present/Absent pair — future attendance statuses show up
        # automatically using their model-declared display label.
        status_display = dict(AttendanceRecord.AttendanceStatus.choices)
        status_counts = OrderedDict()
        for s in attendance_by_date.values():
            status_counts[s] = status_counts.get(s, 0) + 1
        attendance_status_summary = [
            (code, status_display.get(code, code.title()))
            for code in sorted(status_counts)
        ]
        holiday_dates = self._resolve_holiday_dates(attendance_months, placement_class)

        # --- Fees: one figure — what is still owed for the LAST month of the period. A
        # monthly row already carries every earlier unpaid month in its amount_due, so
        # reading one month never double-counts, and a 6-month report reads only its
        # final month. With no period the month is today's, capped at the year's end.
        from finance.models import FeePayment
        if date_to:
            fee_month_date = date_to
        else:
            fee_month_date = timezone.localdate()
            if academic_year_obj and academic_year_obj.end_date < fee_month_date:
                fee_month_date = academic_year_obj.end_date
        fee_rows_qs = FeePayment.objects.filter(
            student=student, year=fee_month_date.year, month=fee_month_date.month,
            handed_over_to_exit__isnull=True,
        )
        if has_history:
            fee_rows_qs = FeePayment.objects.filter(
                timeline.fees_q(segments), year=fee_month_date.year, month=fee_month_date.month,
                handed_over_to_exit__isnull=True,
            )
        # Credits (paid above due) never offset another row's balance.
        fee_outstanding = sum(
            (max((r.amount_due or 0) - (r.amount_paid or 0), 0) for r in fee_rows_qs), 0,
        )
        fee_month_label = fee_month_date.strftime('%b %Y')

        # --- Learning progress: published lessons taught, grouped by subject ---
        # Drafts are never shown to parents, but they are counted so the report can say
        # "still drafts" instead of claiming nothing was taught.
        from lms.models import LessonPlan
        lessons_by_subject = OrderedDict()
        # Whole-class plans plus the student's own section, never a sibling's.
        section_q = Q(session_class__isnull=True)
        if placement is not None and placement.session_class_id:
            section_q |= Q(session_class_id=placement.session_class_id)
        lesson_qs = LessonPlan.objects.filter(
            section_q, class_obj_id=placement_class, is_active=True,
        )
        if date_from and date_to:
            lesson_qs = lesson_qs.filter(lesson_date__range=(date_from, date_to))
        elif academic_year_id:
            lesson_qs = lesson_qs.filter(academic_year_id=academic_year_id)
        draft_lesson_count = lesson_qs.filter(status=LessonPlan.Status.DRAFT).count()
        published = lesson_qs.filter(status=LessonPlan.Status.PUBLISHED).select_related('subject')
        for lp in published.order_by('lesson_date'):
            # display_text is multi-line (chapter / topic / subtopic); one line per lesson
            # reads better in a bullet list than collapsed whitespace.
            topic = ' - '.join(ln.strip() for ln in lp.display_text.splitlines() if ln.strip()) or lp.title
            lessons_by_subject.setdefault(lp.subject.name, []).append(topic)

        # --- Skills / behaviour assessment + remarks (teacher-entered, StudentTermAssessment) ---
        skills_ratings = []
        behaviour_ratings = []
        teacher_remark = ''
        principal_remark = ''
        assessment_exists = False
        assessment_fallback = False
        selected_assessment = None
        assessment_label = ''
        if academic_year_obj:
            try:
                from examinations.models import StudentTermAssessment
                assessments = StudentTermAssessment.objects.filter(
                    student=student,
                    academic_year=academic_year_obj,
                )

                order_map = self._academic_year_month_order(academic_year_obj)
                year_assessments = assessments
                if date_from and date_to:
                    month_sequence = [month for _year, month in self._month_sequence(date_from, date_to)]
                    allowed_months = [month for month in month_sequence if month in order_map]
                    if allowed_months:
                        assessments = assessments.filter(month__in=allowed_months)
                    # Nothing entered inside the period: fall back to the latest earlier
                    # assessment of the year (never a later one) rather than a blank section,
                    # and label its month so it isn't mistaken for the period's own.
                    if not assessments.exists() and date_to.month in order_map:
                        earlier = [a for a in year_assessments if order_map.get(a.month, 99) <= order_map[date_to.month]]
                        if earlier:
                            assessments = year_assessments.filter(id__in=[a.id for a in earlier])
                            assessment_fallback = True

                if assessments.exists():
                    selected_assessment = max(
                        assessments,
                        key=lambda item: (
                            order_map.get(item.month, -1),
                            item.updated_at or item.created_at or datetime.min,
                            item.id or 0,
                        ),
                    )

                if selected_assessment:
                    assessment_exists = True
                    if assessment_fallback:
                        month_year = dict((m, y) for y, m in self._twelve_months_from(academic_year_obj.start_date))
                        assessment_label = date(month_year[selected_assessment.month], selected_assessment.month, 1).strftime('%b %Y')
                    skills_ratings = [
                        ('Listening', selected_assessment.listening), ('Speaking', selected_assessment.speaking),
                        ('Writing', selected_assessment.writing), ('Reading', selected_assessment.reading),
                        ('Participation', selected_assessment.participation), ('Confidence', selected_assessment.confidence),
                        ('Social Skills', selected_assessment.social_skills),
                    ]
                    behaviour_ratings = [
                        ('Discipline', selected_assessment.discipline), ('Respect', selected_assessment.respect),
                        ('Teamwork', selected_assessment.teamwork),
                        ('Class Participation', selected_assessment.class_participation),
                        ('Responsibility', selected_assessment.responsibility),
                    ]
                    teacher_remark = selected_assessment.teacher_remark
                    principal_remark = selected_assessment.principal_remark
            except Exception:
                pass

        # A transferred-in student with no assessment at this branch yet: use the latest one
        # from an earlier branch rather than printing an empty section.
        if has_history and not assessment_exists:
            try:
                from examinations.models import StudentTermAssessment
                earlier_assessment = (
                    StudentTermAssessment.objects
                    .filter(timeline.rows_q([s for s in segments if not s.is_current]))
                    .order_by('-academic_year__start_date', '-month', '-id').first()
                )
                if earlier_assessment:
                    assessment_exists = True
                    a = earlier_assessment
                    skills_ratings = [
                        ('Listening', a.listening), ('Speaking', a.speaking), ('Writing', a.writing),
                        ('Reading', a.reading), ('Participation', a.participation), ('Confidence', a.confidence),
                        ('Social Skills', a.social_skills),
                    ]
                    behaviour_ratings = [
                        ('Discipline', a.discipline), ('Respect', a.respect), ('Teamwork', a.teamwork),
                        ('Class Participation', a.class_participation), ('Responsibility', a.responsibility),
                    ]
                    teacher_remark, principal_remark = a.teacher_remark, a.principal_remark
            except Exception:
                pass

        # --- Header images (best-effort; report renders fine without them) ---
        photo_bytes = fetch_image_bytes(student.photo_url)
        school_logo_bytes = fetch_image_bytes(self.school.logo)

        if date_from and date_to:
            period_label = f"{date_from.strftime('%d %b %Y')} - {date_to.strftime('%d %b %Y')}"
        elif academic_year_obj:
            period_label = f"Academic Year {academic_year_obj.name}"
        elif academic_year_id:
            period_label = "Academic Year"
        else:
            period_label = "All Time"

        gender_display = {'M': 'Male', 'F': 'Female', 'O': 'Other'}.get(student.gender)
        dob_display = student.date_of_birth.strftime('%d %b %Y') if student.date_of_birth else None
        parent_contact = student.parent_phone or student.guardian_phone
        academic_session_display = academic_year_obj.name if academic_year_obj else 'N/A'

        # Class teacher(s) of the student's section for the report's year.
        from academics.models import ClassTeacherAssignment
        teacher_qs = ClassTeacherAssignment.objects.filter(school=self.school, is_active=True)
        if academic_year_obj:
            teacher_qs = teacher_qs.filter(Q(academic_year=academic_year_obj) | Q(academic_year__isnull=True))
        if placement is not None and placement.session_class_id:
            teacher_qs = teacher_qs.filter(session_class_id=placement.session_class_id)
        else:
            teacher_qs = teacher_qs.filter(class_obj_id=placement_class, session_class__isnull=True)
        class_teacher_name = ', '.join(
            a.teacher.full_name for a in teacher_qs.select_related('teacher')
        )

        all_ratings = [r for _label, r in skills_ratings + behaviour_ratings if r]
        skills_avg = round(sum(all_ratings) / len(all_ratings), 1) if all_ratings else None

        student_info_rows = [
            ('Name', student.name),
            ('Class', class_name),
            ('Roll #', str(roll_number)),
        ]
        if class_teacher_name:
            student_info_rows.append(('Class Teacher', class_teacher_name))
        if student.admission_number:
            student_info_rows.append(('Admission #', student.admission_number))
        if dob_display:
            student_info_rows.append(('Date of Birth', dob_display))
        if gender_display:
            student_info_rows.append(('Gender', gender_display))
        student_info_rows.append(('Parent Name', student.parent_name or student.guardian_name or '-'))
        student_info_rows.append(('Parent Contact', format_pk_phone(parent_contact) or '-'))
        student_info_rows.append(('Academic Session', academic_session_display))
        if has_history:
            student_info_rows.append(('Includes Records From', ', '.join(earlier_branches)))

        return {
            'school_name': self.school.name,
            'school_logo_bytes': school_logo_bytes,
            'academic_session_display': academic_session_display,
            'report_period_label': period_label,
            'student_info_rows': student_info_rows,
            'photo_bytes': photo_bytes,
            'attendance_by_date': attendance_by_date,
            'attendance_months': attendance_months,
            'attendance_status_summary': attendance_status_summary,
            'holiday_dates': holiday_dates,
            'present_count': present,
            'absent_count': absent,
            'leave_count': leave,
            'working_days': total_days,
            'attendance_rate': att_rate,
            'fee_month_label': fee_month_label,
            'fee_outstanding': fee_outstanding,
            'lessons_by_subject': lessons_by_subject,
            'draft_lesson_count': draft_lesson_count,
            'skills_avg': skills_avg,
            'skills_ratings': skills_ratings,
            'behaviour_ratings': behaviour_ratings,
            'assessment_exists': assessment_exists,
            'assessment_label': assessment_label,
            'teacher_remark': teacher_remark,
            'principal_remark': principal_remark,
        }

    def render_pdf(self, data):
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import inch
        from reportlab.platypus import (
            HRFlowable, Image, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
        )

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer, pagesize=A4,
            topMargin=0.5 * inch, bottomMargin=0.5 * inch,
            leftMargin=0.55 * inch, rightMargin=0.55 * inch,
        )
        styles = getSampleStyleSheet()
        elements = []

        if data.get('error'):
            elements.append(Paragraph(data['error'], styles['Heading2']))
            doc.build(elements)
            return buffer.getvalue()

        muted_style = ParagraphStyle('Muted', parent=styles['Normal'], fontSize=9.5, textColor=colors.HexColor(GRAY_TEXT))
        body_style = ParagraphStyle('Body', parent=styles['Normal'], fontSize=9.5, leading=13)
        empty_state_style = ParagraphStyle(
            'EmptyState', parent=styles['Normal'], fontSize=8.5,
            textColor=colors.HexColor(GRAY_TEXT), fontName='Helvetica-Oblique',
        )

        # ============================================================
        # HEADER / LETTERHEAD
        # ============================================================
        # Font size shrinks to keep long school names on one line; the gap
        # between all three header lines is a fixed constant so it reads as
        # even regardless of each line's own font size/leading.
        HEADER_LINE_GAP = 4
        logo_bytes = data.get('school_logo_bytes')
        title_max_width = doc.width - (1.0 * inch if logo_bytes else 0) - 4
        title_font_size = fit_title_font_size(data['school_name'], title_max_width)

        school_title_style = ParagraphStyle(
            'SchoolTitle', parent=styles['Heading1'], fontSize=title_font_size,
            leading=title_font_size + 3, spaceBefore=0, spaceAfter=HEADER_LINE_GAP,
        )
        report_title_style = ParagraphStyle(
            'ReportTitle', parent=styles['Normal'], fontSize=14, leading=16,
            textColor=colors.HexColor(BLUE), spaceBefore=0, spaceAfter=HEADER_LINE_GAP,
        )
        session_style = ParagraphStyle(
            'SessionLine', parent=styles['Normal'], fontSize=9.5, leading=11,
            textColor=colors.HexColor(GRAY_TEXT), spaceBefore=0, spaceAfter=0,
        )

        header_text = [
            Paragraph(f"<b>{data['school_name']}</b>", school_title_style),
            Paragraph('Student Report', report_title_style),
            Paragraph(f"Academic Session: {data['academic_session_display']}", session_style),
        ]
        if logo_bytes:
            try:
                logo = Image(io.BytesIO(logo_bytes), width=0.8 * inch, height=0.8 * inch)
                header_row = Table([[logo, header_text]], colWidths=[1.0 * inch, None])
                header_row.setStyle(TableStyle([
                    ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                    ('LEFTPADDING', (0, 0), (-1, -1), 0),
                ]))
                elements.append(header_row)
            except Exception:
                elements.extend(header_text)
        else:
            elements.extend(header_text)

        elements.append(Spacer(1, 8))
        elements.append(HRFlowable(width='100%', thickness=2, color=colors.HexColor(BLUE), spaceAfter=12))

        # ============================================================
        # STUDENT PROFILE CARD
        # ============================================================
        info_label_style = ParagraphStyle('InfoLabel', parent=styles['Normal'], fontSize=8.5, textColor=colors.HexColor(GRAY_TEXT))
        info_rows = data.get('student_info_rows', [])
        info_table_data = []
        for i in range(0, len(info_rows), 2):
            pair = info_rows[i:i + 2]
            row = []
            for label, value in pair:
                row.append(Paragraph(f"<font color='{GRAY_TEXT}'>{label}</font><br/><b>{value}</b>", info_label_style))
            if len(pair) == 1:
                row.append('')
            info_table_data.append(row)
        info_grid = Table(info_table_data, colWidths=[2.55 * inch, 2.55 * inch])
        info_grid.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('LEFTPADDING', (0, 0), (-1, -1), 0),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
        ]))

        photo_bytes = data.get('photo_bytes')
        if photo_bytes:
            try:
                photo_cell = Image(io.BytesIO(photo_bytes), width=1.15 * inch, height=1.15 * inch)
            except Exception:
                photo_cell = build_photo_placeholder()
        else:
            photo_cell = build_photo_placeholder()

        info_card_inner = Table([[info_grid, photo_cell]], colWidths=[None, 1.3 * inch])
        info_card_inner.setStyle(TableStyle([
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('ALIGN', (1, 0), (1, 0), 'RIGHT'),
            ('LEFTPADDING', (0, 0), (-1, -1), 0),
            ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ]))
        info_card = Table([[info_card_inner]], colWidths=[CONTENT_WIDTH])
        info_card.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor(CARD_BG)),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor(GRAY_BORDER)),
            ('ROUNDEDCORNERS', [8, 8, 8, 8]),
            ('TOPPADDING', (0, 0), (-1, -1), 12),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
            ('LEFTPADDING', (0, 0), (-1, -1), 14),
            ('RIGHTPADDING', (0, 0), (-1, -1), 14),
        ]))
        elements.append(info_card)
        elements.append(Spacer(1, 12))

        # ============================================================
        # SUMMARY STRIP
        # ============================================================
        summary_cards = [
            (f"{data['attendance_rate']}%" if data['working_days'] else '-', 'Attendance %', INFO_BG, INFO_TEXT),
            (str(data['absent_count']), 'Days Absent', ABSENT_BG, ABSENT_TEXT),
        ]
        if data.get('skills_avg') is not None:
            summary_cards.append((f"{data['skills_avg']}/5", 'Skills & Behaviour', LEAVE_BG, LEAVE_TEXT))
        owes = data['fee_outstanding'] > 0
        summary_cards.append((
            f"{data['fee_outstanding']:,.0f}" if owes else 'Clear',
            f"Outstanding {data['fee_month_label']} (PKR)" if owes else f"Fees {data['fee_month_label']}",
            ABSENT_BG if owes else PRESENT_BG, ABSENT_TEXT if owes else PRESENT_TEXT,
        ))
        elements.append(build_stat_cards(summary_cards))
        elements.append(Spacer(1, 14))

        # ============================================================
        # ATTENDANCE (page 1)
        # ============================================================
        elements.append(section_heading('Attendance', styles))
        elements.append(Spacer(1, 8))
        if data['attendance_by_date']:
            legend_items = [
                (ATTENDANCE_STATUS_COLORS.get(code, DEFAULT_STATUS_COLOR)[0], label)
                for code, label in data['attendance_status_summary']
            ]
            if data.get('holiday_dates'):
                legend_items.append((OFF_DAY_BG, 'Off Day'))
            elements.append(build_legend(legend_items))
            elements.append(Spacer(1, 8))
            for year, month in data['attendance_months']:
                elements.append(KeepTogether(build_month_grid_flowables(year, month, data['attendance_by_date'], data.get('holiday_dates'))))
                elements.append(Spacer(1, 10))
            elements.append(build_stat_cards([
                (str(data['present_count']), 'Present', PRESENT_BG, PRESENT_TEXT),
                (str(data['absent_count']), 'Absent', ABSENT_BG, ABSENT_TEXT),
                (str(data['leave_count']), 'Leave', LEAVE_BG, LEAVE_TEXT),
                (f"{data['attendance_rate']}%", 'Attendance %', INFO_BG, INFO_TEXT),
                (str(data['working_days']), 'Working Days', NEUTRAL_BG, NEUTRAL_TEXT),
            ]))
            elements.append(Spacer(1, 6))
            elements.append(Paragraph(f"Report Period: {data['report_period_label']}", muted_style))
            elements.append(Spacer(1, 12))
        else:
            elements.append(Paragraph('No attendance records for this period.', empty_state_style))

        # --- Learning Progress ---
        learning = [section_heading('Learning Progress', styles), Spacer(1, 8)]
        lessons_by_subject = data.get('lessons_by_subject') or {}
        if lessons_by_subject:
            for subject, topics in lessons_by_subject.items():
                learning.append(KeepTogether([
                    Paragraph(f"<b>{subject}</b>", body_style),
                    Paragraph('<br/>'.join(f'• {t}' for t in topics), body_style),
                    Spacer(1, 8),
                ]))
        elif data.get('draft_lesson_count'):
            n = data['draft_lesson_count']
            learning.append(Paragraph(
                f"{n} lesson plan{'s' if n != 1 else ''} for this period "
                f"{'are' if n != 1 else 'is'} still in draft and not yet published by the teacher.",
                empty_state_style,
            ))
        else:
            learning.append(Paragraph('No lessons recorded for this period.', empty_state_style))
        learning.append(Spacer(1, 14))
        elements.append(KeepTogether(learning[:3]))
        elements.extend(learning[3:])

        # --- Skills Assessment ---
        elements.append(section_heading('Skills Assessment', styles))
        elements.append(Spacer(1, 8))
        if data.get('assessment_label'):
            elements.append(Paragraph(f"Latest assessment on record: {data['assessment_label']}", empty_state_style))
            elements.append(Spacer(1, 4))
        if data['assessment_exists']:
            elements.append(build_two_column_ratings(data['skills_ratings']))
        else:
            elements.append(Paragraph('Not yet assessed.', empty_state_style))
        elements.append(Spacer(1, 14))

        # --- Behaviour Evaluation ---
        elements.append(section_heading('Behaviour Evaluation', styles))
        elements.append(Spacer(1, 8))
        if data.get('assessment_label'):
            elements.append(Paragraph(f"Latest assessment on record: {data['assessment_label']}", empty_state_style))
            elements.append(Spacer(1, 4))
        if data['assessment_exists']:
            elements.append(build_two_column_ratings(data['behaviour_ratings']))
        else:
            elements.append(Paragraph('Not yet assessed.', empty_state_style))
        elements.append(Spacer(1, 14))

        # --- Fees: a single figure for the period's last month, or a cleared banner ---
        elements.append(section_heading('Fees', styles))
        elements.append(Spacer(1, 8))
        if data['fee_outstanding'] > 0:
            elements.append(build_stat_cards([
                (f"{data['fee_outstanding']:,.0f}", f"Outstanding for {data['fee_month_label']} (PKR)", ABSENT_BG, ABSENT_TEXT),
            ]))
        else:
            banner_style = ParagraphStyle(
                'FeesClearedBanner', parent=styles['Normal'], fontSize=10.5,
                textColor=colors.HexColor(PRESENT_TEXT), alignment=1,
            )
            banner = Table(
                [[Paragraph(f"<b>All dues cleared for {data['fee_month_label']}</b>", banner_style)]],
                colWidths=[CONTENT_WIDTH],
            )
            banner.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor(PRESENT_BG)),
                ('ROUNDEDCORNERS', [6, 6, 6, 6]),
                ('TOPPADDING', (0, 0), (-1, -1), 10),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
            ]))
            elements.append(banner)
        elements.append(Spacer(1, 14))

        # --- Remarks ---
        remark_box_style = TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor(CARD_BG)),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor(GRAY_BORDER)),
            ('ROUNDEDCORNERS', [6, 6, 6, 6]),
            ('TOPPADDING', (0, 0), (-1, -1), 10),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
            ('LEFTPADDING', (0, 0), (-1, -1), 10),
            ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ])

        elements.append(section_heading('Teacher Remarks', styles))
        elements.append(Spacer(1, 8))
        teacher_remark_raw = data['teacher_remark'].replace('‑', '-').strip() if data['teacher_remark'] else ''
        teacher_remark_text = teacher_remark_raw or 'No remarks provided.'
        teacher_remark_style = body_style if teacher_remark_raw else empty_state_style
        teacher_box = Table([[Paragraph(teacher_remark_text, teacher_remark_style)]], colWidths=[CONTENT_WIDTH])
        teacher_box.setStyle(remark_box_style)
        elements.append(teacher_box)
        elements.append(Spacer(1, 14))

        elements.append(section_heading('Principal Remarks', styles))
        elements.append(Spacer(1, 8))
        principal_remark_raw = data['principal_remark'].replace('‑', '-').strip() if data['principal_remark'] else ''
        principal_remark_text = principal_remark_raw or 'No remarks provided.'
        principal_remark_style = body_style if principal_remark_raw else empty_state_style
        principal_box = Table([[Paragraph(principal_remark_text, principal_remark_style)]], colWidths=[CONTENT_WIDTH])
        principal_box.setStyle(remark_box_style)
        elements.append(principal_box)
        elements.append(Spacer(1, 36))

        # --- Signatures ---
        sig_label_style = ParagraphStyle('SigLabel', parent=styles['Normal'], fontSize=9, textColor=colors.HexColor(GRAY_TEXT), alignment=1)
        sig_table = Table(
            [
                ['_________________________', '_________________________', '_________________________'],
                [Paragraph('Teacher Signature', sig_label_style), Paragraph('Principal Signature', sig_label_style), Paragraph('Date', sig_label_style)],
            ],
            colWidths=[CONTENT_WIDTH / 3] * 3,
        )
        sig_table.setStyle(TableStyle([
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 1), (-1, 1), 4),
        ]))
        elements.append(sig_table)

        # --- Footer: drawn on every page via canvas so page numbers ("Page X of Y")
        # are correct without a second render pass, and the footer always sits at a
        # fixed position at the bottom of the page rather than floating in-flow.
        doc.build(elements, canvasmaker=_make_footer_canvas(doc, self.school.name))
        return buffer.getvalue()
