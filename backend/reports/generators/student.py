def build_month_grid_flowables(year, month, attendance_by_date, holiday_dates=None):
    """
    Calendar-style Table for one month, cells colored by attendance status
    (whatever status codes are present in the data) or, absent a record,
    by whether the date is a school-calendar off day. Returns a list of
    flowables (month title + table).
    """
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import Paragraph, Table, TableStyle

    holiday_dates = holiday_dates or set()
    styles = getSampleStyleSheet()
    cal = calendar.Calendar(firstweekday=6)  # Sunday-first
    weeks = cal.monthdayscalendar(year, month)

    header = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
    table_data = [header] + [
        [str(day) if day else '' for day in week] for week in weeks
    ]

    # Full content width, so the grid lines up with the stat cards and section headings.
    col_width = CONTENT_WIDTH / 7
    table = Table(table_data, colWidths=[col_width] * 7, hAlign='LEFT')
    style_cmds = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor(BLUE)),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor(GRAY_BORDER)),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('TOPPADDING', (0, 0), (-1, -1), 7),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
    ]
    for r, week in enumerate(weeks, start=1):
        for c, day in enumerate(week):
            if not day:
                style_cmds.append(('BACKGROUND', (c, r), (c, r), colors.HexColor('#F9FAFB')))
                continue
            d = date(year, month, day)
            status = attendance_by_date.get(d)
            if status:
                bg, _text = ATTENDANCE_STATUS_COLORS.get(status, DEFAULT_STATUS_COLOR)
            elif d in holiday_dates:
                bg = OFF_DAY_BG
            else:
                bg = None
            if bg:
                style_cmds.append(('BACKGROUND', (c, r), (c, r), colors.HexColor(bg)))
    table.setStyle(TableStyle(style_cmds))

    month_style = ParagraphStyle(
        'MonthTitle', parent=styles['Normal'], fontSize=11,
        textColor=colors.HexColor(BLUE), spaceAfter=3,
    )
    month_label = date(year, month, 1).strftime('%B %Y')
    return [Paragraph(f"<b>{month_label}</b>", month_style), table]


