def _make_footer_canvas(doc, school_name):
    """
    Build a Canvas subclass that draws a running footer (school name + generated
    timestamp on the left, "Page X of Y" on the right) at a fixed position on
    every page. Buffers pages via showPage() so the total page count is known
    by the time save() draws each footer.
    """
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import inch
    from reportlab.pdfgen import canvas as pdfcanvas

    generated_line = f"{school_name} | Generated by Education AI | {timezone.localtime().strftime('%d %B %Y at %I:%M %p')}"

    class NumberedFooterCanvas(pdfcanvas.Canvas):
        def __init__(self, *args, **kwargs):
            pdfcanvas.Canvas.__init__(self, *args, **kwargs)
            self._saved_page_states = []

        def showPage(self):
            self._saved_page_states.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total_pages = len(self._saved_page_states)
            for state in self._saved_page_states:
                self.__dict__.update(state)
                self._draw_footer(total_pages)
                pdfcanvas.Canvas.showPage(self)
            pdfcanvas.Canvas.save(self)

        def _draw_footer(self, total_pages):
            left_margin = doc.leftMargin
            right_edge = A4[0] - doc.rightMargin
            line_y = 0.4 * inch
            text_y = 0.25 * inch
            self.setStrokeColor(colors.HexColor(GRAY_BORDER))
            self.setLineWidth(0.5)
            self.line(left_margin, line_y, right_edge, line_y)
            self.setFont('Helvetica', 8)
            self.setFillColor(colors.HexColor(GRAY_TEXT))
            self.drawString(left_margin, text_y, generated_line)
            self.drawRightString(right_edge, text_y, f"Page {self._pageNumber} of {total_pages}")

    return NumberedFooterCanvas


def _month_range_q(date_from, date_to):
    """
    Build a Q filter over integer year/month fields (as used by FeePayment)
    spanning a date range.
    """
    y1, m1 = date_from.year, date_from.month
    y2, m2 = date_to.year, date_to.month
    if y1 == y2:
        return Q(year=y1, month__gte=m1, month__lte=m2)
    return (
        Q(year=y1, month__gte=m1)
        | Q(year__gt=y1, year__lt=y2)
        | Q(year=y2, month__lte=m2)
    )


def format_pk_phone(phone):
    """Format an 11-digit Pakistani mobile number as 0XXX-XXXXXXX; returns input unchanged if it doesn't match."""
    if not phone:
        return phone
    digits = re.sub(r'\D', '', phone)
    if len(digits) == 11 and digits.startswith('0'):
        return f"{digits[:4]}-{digits[4:]}"
    return phone


def fetch_image_bytes(url, timeout=5):
    """Best-effort image download — returns None on any failure so callers can render without it."""
    if not url:
        return None
    try:
        from core.url_safety import assert_safe_external_url
        assert_safe_external_url(url)
        import requests
        resp = requests.get(url, timeout=timeout)
        if resp.status_code == 200:
            return resp.content
    except Exception:
        pass
    return None


def fit_title_font_size(text, max_width, font_name='Helvetica-Bold', max_size=23, min_size=13):
    """Largest font size (down to min_size) at which `text` still fits on one line within max_width."""
    from reportlab.pdfbase.pdfmetrics import stringWidth

    size = max_size
    while size > min_size and stringWidth(text, font_name, size) > max_width:
        size -= 1
    return size


# --- Small vector-drawn building blocks -----------------------------------
# Ratings render as drawn star polygons rather than Unicode "★" glyphs:
# reportlab's default Helvetica/base-14 fonts only cover the Latin-1/WinAnsi
# range and don't reliably render U+2605, so a literal string risks blank
# or broken glyphs in the PDF. Drawing shapes sidesteps that entirely.

def _star_points(cx, cy, outer_r, inner_r):
    points = []
    for i in range(10):
        angle = math.pi / 2 + i * math.pi / 5
        r = outer_r if i % 2 == 0 else inner_r
        points.extend([cx + r * math.cos(angle), cy + r * math.sin(angle)])
    return points


def draw_rating_stars(rating, max_stars=5, size=10, gap=2):
    """Small Drawing flowable: max_stars vector stars, `rating` of them filled."""
    from reportlab.graphics.shapes import Drawing, Polygon
    from reportlab.lib import colors

    filled = colors.HexColor('#F59E0B')
    empty = colors.HexColor('#E5E7EB')
    width = max_stars * (size + gap)
    drawing = Drawing(width, size)
    outer_r, inner_r = size / 2, size / 2 * 0.42
    for i in range(max_stars):
        cx = i * (size + gap) + outer_r
        pts = _star_points(cx, outer_r, outer_r, inner_r)
        fill = filled if rating and i < rating else empty
        drawing.add(Polygon(pts, fillColor=fill, strokeColor=fill))
    return drawing


def section_heading(text, styles):
    """Section heading with a colored left-accent bar in place of a literal icon glyph."""
    from reportlab.lib import colors
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.platypus import Paragraph, Table, TableStyle

