// Builds the pages the mobile app shows in a WebView, from the web's own code, so mobile and web share one definition:
//   - the question-text editor  (frontend/src/components/richEditorCore.js + richEditorEntry.js) -> mobile/assets/richEditorHtml.ts
//   - the figure drawing pad    (frontend/src/components/diagramDraw.js + diagramEntry.js)       -> mobile/assets/diagramPadHtml.ts
//
//   node scripts/build-rich-editor.mjs          writes both files
//   node scripts/build-rich-editor.mjs --check  fails if either is out of date (run after changing the shared files)
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const frontend = path.join(root, 'frontend')
const require = createRequire(path.join(frontend, 'package.json'))
const esbuild = require('esbuild')
const check = process.argv.includes('--check')

async function bundle(entry) {
  const built = await esbuild.build({
    entryPoints: [path.join(frontend, 'src', 'components', entry)],
    bundle: true, minify: true, write: false, platform: 'browser', format: 'iife', target: 'es2019', legalComments: 'none', logLevel: 'error',
    nodePaths: [path.join(frontend, 'node_modules')],
  })
  return built.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
}

const head = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">'

// KaTeX styles so equations render in the editor; the font files are left out (about 260 KB), so symbols use system fonts.
const katexCss = fs.readFileSync(path.join(frontend, 'node_modules', 'katex', 'dist', 'katex.min.css'), 'utf8').replace(/@font-face\{[^}]*\}/g, '')

const editorCss = `
html,body{margin:0;padding:0;background:#fff;color:#0f172a;font:16px/1.5 -apple-system,Roboto,"Segoe UI",sans-serif;-webkit-text-size-adjust:100%}
body.rtl{font-family:"Noto Nastaliq Urdu","Noto Naskh Arabic","Jameel Noori Nastaleeq",Roboto,sans-serif;line-height:2}
#editor{min-height:120px;padding:10px 12px;box-sizing:border-box}
#editor .ProseMirror{outline:none;min-height:100px}
#editor.empty .ProseMirror:before{content:attr(data-placeholder);color:#94a3b8;position:absolute;pointer-events:none}
#editor p{margin:0 0 .5em}
#editor table{border-collapse:collapse;margin:.5em 0;table-layout:fixed;width:100%}
#editor td,#editor th{border:1px solid #cbd5e1;padding:4px 6px;vertical-align:top;min-width:1em;position:relative}
#editor th{background:#f1f5f9;font-weight:600}
#editor .selectedCell:after{content:"";position:absolute;inset:0;background:rgba(59,130,246,.15);pointer-events:none}
#editor ul,#editor ol{padding-inline-start:1.4em;margin:.3em 0}
#editor blockquote{border-inline-start:3px solid #cbd5e1;margin:.5em 0;padding-inline-start:.8em;color:#475569}
#editor code{background:#f1f5f9;border-radius:3px;padding:0 3px}
#editor .tableWrapper{overflow-x:auto}
${katexCss}`

const padCss = `
html,body{margin:0;padding:0;background:#f8fafc;overflow:hidden;touch-action:none;height:100%}
#pad{display:block;width:100%;height:auto;max-height:100%;background:#fff;touch-action:none;box-sizing:border-box;border:1px solid #cbd5e1}`

const pages = [
  { file: 'richEditorHtml.ts', name: 'RICH_EDITOR', entry: 'richEditorEntry.js', html: (js) => `${head}<style>${editorCss}</style></head><body><div id="editor" data-placeholder=""></div><script>${js}</script></body></html>` },
  { file: 'diagramPadHtml.ts', name: 'DIAGRAM_PAD', entry: 'diagramEntry.js', html: (js) => `${head}<style>${padCss}</style></head><body><canvas id="pad"></canvas><script>${js}</script></body></html>` },
]

let stale = false
for (const page of pages) {
  const html = page.html(await bundle(page.entry))
  const hash = crypto.createHash('sha256').update(html).digest('hex').slice(0, 16)
  const out = path.join(root, 'mobile', 'assets', page.file)
  const file = `// GENERATED by scripts/build-rich-editor.mjs from frontend/src/components (${page.entry}). Do not edit.\nexport const ${page.name}_HASH = '${hash}';\nexport const ${page.name}_HTML = ${JSON.stringify(html)};\n`
  if (check) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
    if (current !== file) { console.error(`mobile/assets/${page.file} is out of date: run node scripts/build-rich-editor.mjs`); stale = true } else console.log(`${page.file} is up to date (${hash})`)
  } else {
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, file)
    console.log(`wrote mobile/assets/${page.file} (${Math.round(html.length / 1024)} KB, ${hash})`)
  }
}
if (stale) process.exit(1)
